CREATE OR REPLACE FUNCTION public.commissioner_set_structure_active(p_entity_type TEXT, p_entity_id BIGINT, p_active BOOLEAN)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.is_commissioner_user(auth.uid()) THEN RAISE EXCEPTION 'Commissioner access required.'; END IF;
  CASE p_entity_type
    WHEN 'league' THEN UPDATE public.season_leagues SET active=p_active,updated_at=NOW() WHERE id=p_entity_id;
    WHEN 'conference' THEN UPDATE public.season_conferences SET active=p_active,updated_at=NOW() WHERE id=p_entity_id;
    WHEN 'division' THEN UPDATE public.season_divisions SET active=p_active,updated_at=NOW() WHERE id=p_entity_id;
    ELSE RAISE EXCEPTION 'Unknown structure type.';
  END CASE;
END; $$;

CREATE OR REPLACE FUNCTION public.commissioner_save_data_source(p_id BIGINT, p_league_id BIGINT, p_source_type TEXT, p_source_name TEXT, p_starts_on DATE, p_ends_on DATE, p_priority INT, p_configuration JSONB DEFAULT '{}'::jsonb, p_active BOOLEAN DEFAULT TRUE)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE saved_id BIGINT;
BEGIN
  IF NOT public.is_commissioner_user(auth.uid()) THEN RAISE EXCEPTION 'Commissioner access required.'; END IF;
  IF p_source_type NOT IN ('mlb_stats_api','simulation','spreadsheet','manual','other_api') THEN RAISE EXCEPTION 'Unknown data source type.'; END IF;
  IF p_ends_on IS NOT NULL AND p_ends_on < p_starts_on THEN RAISE EXCEPTION 'End date cannot precede start date.'; END IF;
  IF p_id IS NULL THEN
    INSERT INTO public.league_data_source_periods(league_id,source_type,source_name,starts_on,ends_on,priority,configuration,active,created_by)
    VALUES(p_league_id,p_source_type,trim(p_source_name),p_starts_on,p_ends_on,p_priority,COALESCE(p_configuration,'{}'::jsonb),p_active,auth.uid()) RETURNING id INTO saved_id;
  ELSE
    UPDATE public.league_data_source_periods SET league_id=p_league_id,source_type=p_source_type,source_name=trim(p_source_name),starts_on=p_starts_on,ends_on=p_ends_on,priority=p_priority,configuration=COALESCE(p_configuration,'{}'::jsonb),active=p_active,updated_at=NOW() WHERE id=p_id RETURNING id INTO saved_id;
  END IF;
  RETURN saved_id;
END; $$;

CREATE OR REPLACE FUNCTION public.league_data_source_for_date(p_league_id BIGINT, p_stat_date DATE)
RETURNS TABLE(source_type TEXT, source_name TEXT, configuration JSONB) LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT p.source_type,p.source_name,p.configuration FROM public.league_data_source_periods p
  WHERE p.league_id=p_league_id AND p.active AND p.starts_on<=p_stat_date AND (p.ends_on IS NULL OR p.ends_on>=p_stat_date)
  ORDER BY p.priority DESC,p.starts_on DESC,p.id DESC LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.commissioner_upsert_team_structure(p_team_name TEXT, p_city TEXT, p_nickname TEXT, p_active BOOLEAN, p_season_id BIGINT, p_division_id BIGINT)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE saved_team_id BIGINT; saved_assignment_id BIGINT; target_division public.season_divisions%ROWTYPE; target_conference public.season_conferences%ROWTYPE; target_league public.season_leagues%ROWTYPE;
BEGIN
  IF NOT public.is_commissioner_user(auth.uid()) THEN RAISE EXCEPTION 'Commissioner access required.'; END IF;
  IF nullif(trim(p_team_name),'') IS NULL THEN RAISE EXCEPTION 'Team name is required.'; END IF;
  SELECT * INTO target_division FROM public.season_divisions WHERE id=p_division_id AND active;
  SELECT * INTO target_conference FROM public.season_conferences WHERE id=target_division.conference_id AND active;
  SELECT * INTO target_league FROM public.season_leagues WHERE id=target_conference.league_id AND season_id=p_season_id AND active;
  IF target_league.id IS NULL THEN RAISE EXCEPTION 'Choose an active Division in this Season.'; END IF;
  SELECT id INTO saved_team_id FROM public.teams WHERE lower(name)=lower(trim(p_team_name)) LIMIT 1;
  IF saved_team_id IS NULL THEN
    INSERT INTO public.teams(name,city,nickname,active) VALUES(trim(p_team_name),nullif(trim(p_city),''),nullif(trim(p_nickname),''),p_active) RETURNING id INTO saved_team_id;
  ELSE
    UPDATE public.teams SET name=trim(p_team_name),city=nullif(trim(p_city),''),nickname=nullif(trim(p_nickname),''),active=p_active,updated_at=NOW() WHERE id=saved_team_id;
  END IF;
  INSERT INTO public.season_team_assignments(season_id,team_id,league_code,conference_code,division_code,league_id,conference_id,division_id,sort_order)
  VALUES(p_season_id,saved_team_id,target_league.name,target_conference.name,target_division.name,target_league.id,target_conference.id,target_division.id,(SELECT COALESCE(MAX(sort_order),0)+1 FROM public.season_team_assignments WHERE season_id=p_season_id))
  ON CONFLICT(season_id,team_id) DO UPDATE SET league_code=EXCLUDED.league_code,conference_code=EXCLUDED.conference_code,division_code=EXCLUDED.division_code,league_id=EXCLUDED.league_id,conference_id=EXCLUDED.conference_id,division_id=EXCLUDED.division_id
  RETURNING id INTO saved_assignment_id;
  RETURN saved_team_id;
END; $$;

